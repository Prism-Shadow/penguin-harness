#!/usr/bin/env node
/**
 * gen-cli-modules: the CLI modules a package ships, as a generated TS module. A shipped CLI
 * module is a plugin's `./cli` export (core's `CliModule`): every plugin among the package's
 * `dependencies` — an `@penguinharness/*` package, the plugin library host's own rule — whose
 * package.json `exports` names `./cli` is one, in package-name order. Each entry imports its
 * module when the CLI asks for it (`load`), so a module that throws while it evaluates is that
 * module's failure alone; the import is still static enough for the build to bundle it. The list
 * follows the dependencies instead of a hand-kept table: a plugin the CLI depends on that adds a
 * `./cli` export is listed by the next build.
 *
 *   node scripts/gen-cli-modules.mjs --package packages/cli --out packages/cli/src/cli-modules.gen.ts [--check]
 *
 * The CLI's `gen:ifaces` runs it beside gen-ifaces's command table, so typecheck, test and build
 * regenerate it. A dependency is read where Node resolves it from the package
 * (`<package>/node_modules/<name>`); one that is not installed there is an error, not a skip — a
 * list that silently loses a module ships a CLI without its commands.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** The scope every plugin package is published under (core's plugin library host reads the same). */
const PLUGIN_PKG_PREFIX = "@penguinharness/";

/** Whether a package.json's `exports` names the `./cli` subpath. */
function exportsCli(manifest) {
  const exports = manifest.exports;
  return typeof exports === "object" && exports !== null && !Array.isArray(exports)
    ? Object.hasOwn(exports, "./cli")
    : false;
}

/** The plugin dependencies of the package at `dir` that export `./cli`, in package-name order. */
export function shippedCliPackages(dir) {
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const names = Object.keys(manifest.dependencies ?? {})
    .filter((name) => name.startsWith(PLUGIN_PKG_PREFIX))
    .sort();
  return names.filter((name) => {
    const file = path.join(dir, "node_modules", name, "package.json");
    let dependency;
    try {
      dependency = JSON.parse(fs.readFileSync(file, "utf8"));
    } catch (err) {
      // The package is the actionable fact (what to install); the path and the cause follow.
      const cause = err instanceof Error ? err.message : String(err);
      throw new Error(
        `gen-cli-modules: ${name}, a dependency of ${manifest.name ?? dir}, is not installed (${file}: ${cause}) — run pnpm install`,
      );
    }
    return exportsCli(dependency);
  });
}

/** The generated module's text for `names`, as `shippedCliPackages` returns them. */
export function renderCliModules(names) {
  const lines = [
    "/**",
    " * Generated by scripts/gen-cli-modules.mjs — the CLI modules this package ships: every",
    " * plugin dependency (`@penguinharness/*`) whose package.json exports `./cli`, in",
    " * package-name order. Do not edit; regenerate with `pnpm gen:ifaces`.",
    " */",
    'import type { CliModule } from "@prismshadow/penguin-core/cli";',
    "",
    "/** The shipped CLI modules: each package, and the import of its `./cli` default export. */",
    "export const shippedCliModules: readonly {",
    "  package: string;",
    "  load: () => Promise<CliModule>;",
    "}[] = [",
    ...names.map(
      (name) =>
        `  { package: ${JSON.stringify(name)}, load: async () => (await import(${JSON.stringify(`${name}/cli`)})).default },`,
    ),
    "];",
  ];
  return `${lines.join("\n")}\n`;
}

function main(argv) {
  const opt = (flag) => {
    const at = argv.indexOf(flag);
    return at === -1 ? null : (argv[at + 1] ?? null);
  };
  const dir = opt("--package");
  const out = opt("--out");
  if (dir === null || out === null) {
    console.error("usage: gen-cli-modules --package <dir> --out <file.gen.ts> [--check]");
    process.exit(2);
  }
  const text = renderCliModules(shippedCliPackages(dir));
  const existing = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
  if (argv.includes("--check")) {
    if (existing !== text) {
      console.error(`gen-cli-modules: ${out} is stale — run \`pnpm gen:ifaces\``);
      process.exit(1);
    }
  } else if (existing !== text) {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, text);
    console.log(`gen-cli-modules: wrote ${out}`);
  }
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main(process.argv.slice(2));
}
