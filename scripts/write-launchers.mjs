/**
 * Writes a release package's `bin/` launchers.
 *
 *   node scripts/write-launchers.mjs <payload-dir> posix|windows
 *
 * This is the one spelling of the payload layout every install has:
 *
 *     penguin/
 *       bin/{penguin,penguin.cmd}
 *       lib/dist/penguin.js      the CLI entry
 *       web/                     the web assets
 *       node/                    a bundled runtime, optional
 *
 * .github/workflows/release.yml calls it for each package it assembles. Nothing else needs
 * it: a remote install downloads a release rather than being handed a tree, and the desktop
 * app's own launchers run on Electron and live in packages/desktop/src/launcher.ts.
 *
 * The two forms are exclusive, not additive: a POSIX package has no use for penguin.cmd, and
 * the Windows package ships the .cmd alone (a bare `penguin` shell script on PATH would be
 * picked up by Git Bash and run the wrong thing).
 *
 * scripts/test-installer.sh pins the layout markers below.
 */
import fs from "node:fs";
import path from "node:path";

/** `bin/penguin`, chmod 755. Resolves through the ~/.local/bin symlink the installers leave. */
function posixLauncher() {
  return `#!/bin/sh
# penguin launcher (generated by scripts/write-launchers.mjs).

# This script's real location; readlink -f is not portable to macOS, hence the loop.
SOURCE=$0
while [ -h "$SOURCE" ]; do
  DIR=$(cd -P "$(dirname "$SOURCE")" >/dev/null 2>&1 && pwd)
  SOURCE=$(readlink "$SOURCE")
  case $SOURCE in
    /*) ;;
    *) SOURCE="$DIR/$SOURCE" ;;
  esac
done
DIR=$(dirname "$(cd -P "$(dirname "$SOURCE")" >/dev/null 2>&1 && pwd)")

export PENGUIN_WEB_DIST="\${PENGUIN_WEB_DIST:-$DIR/web}"
if [ -x "$DIR/node/bin/node" ]; then
  exec "$DIR/node/bin/node" "$DIR/lib/dist/penguin.js" "$@"
fi
exec node "$DIR/lib/dist/penguin.js" "$@"
`;
}

/**
 * `bin\\penguin.cmd`. Deliberately no `.ps1` sibling: PowerShell prefers `.ps1` on PATH and the
 * default Restricted execution policy would then break the plain `penguin` command, while batch
 * files are exempt. CRLF on purpose — cmd.exe is unreliable with bare LF.
 */
function windowsLauncher() {
  return [
    "@echo off",
    "rem penguin launcher (generated by scripts/write-launchers.mjs).",
    "setlocal",
    'set "DIR=%~dp0.."',
    'if not defined PENGUIN_WEB_DIST set "PENGUIN_WEB_DIST=%DIR%\\web"',
    // Only the Windows release package carries MinGit; elsewhere the guard is simply false.
    'if exist "%DIR%\\git\\usr\\bin\\sh.exe" set "PENGUIN_BUNDLED_SHELL=%DIR%\\git\\usr\\bin\\sh.exe"',
    'if exist "%DIR%\\node\\node.exe" (',
    '  "%DIR%\\node\\node.exe" "%DIR%\\lib\\dist\\penguin.js" %*',
    ") else (",
    '  node "%DIR%\\lib\\dist\\penguin.js" %*',
    ")",
    "exit /b %ERRORLEVEL%",
    "",
  ].join("\r\n");
}

const [payloadDir, form] = process.argv.slice(2);
if (!payloadDir || (form !== "posix" && form !== "windows")) {
  console.error("usage: node scripts/write-launchers.mjs <payload-dir> posix|windows");
  process.exit(2);
}

const binDir = path.join(payloadDir, "bin");
fs.mkdirSync(binDir, { recursive: true });
if (form === "posix") {
  fs.rmSync(path.join(binDir, "penguin.cmd"), { force: true });
  fs.writeFileSync(path.join(binDir, "penguin"), posixLauncher(), { mode: 0o755 });
  // The mode option only applies when writeFileSync creates the file.
  fs.chmodSync(path.join(binDir, "penguin"), 0o755);
} else {
  fs.rmSync(path.join(binDir, "penguin"), { force: true });
  fs.writeFileSync(path.join(binDir, "penguin.cmd"), windowsLauncher());
}
console.log(`[launchers] ${form} → ${binDir}`);
