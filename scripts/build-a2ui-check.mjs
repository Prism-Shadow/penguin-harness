#!/usr/bin/env node
/**
 * Bundles the a2ui checker (packages/core/src/a2ui/cli.ts) into the ONE self-contained ESM file
 * the a2ui skill ships: plugins/a2ui/skills/a2ui/scripts/check.mjs. Node builtins only, no
 * dependencies, not minified — the file is installed into every agent's skills directory and
 * should stay readable to whoever reviews what runs there.
 *
 * The bundle's second line records a sha256 over the a2ui sources. A core test
 * (test/a2ui-skill.test.ts) recomputes it from the checkout and fails when the committed bundle
 * is stale, so a grammar change cannot ship without the checker that enforces it. The test
 * imports the hash helpers from this module and never needs esbuild.
 *
 * Usage: pnpm build:a2ui-check   (node scripts/build-a2ui-check.mjs)
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCES_DIR = path.join(ROOT, "packages/core/src/a2ui");
export const BUNDLE_PATH = path.join(ROOT, "plugins/a2ui/skills/a2ui/scripts/check.mjs");
export const HASH_MARKER = "// a2ui-sources-sha256: ";

/** sha256 over the sorted `*.ts` sources (name and LF-normalized content), hex. */
export function hashA2uiSources(dir = SOURCES_DIR) {
  const hash = createHash("sha256");
  for (const name of fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".ts"))
    .sort()) {
    hash.update(name);
    hash.update("\0");
    hash.update(fs.readFileSync(path.join(dir, name), "utf8").replace(/\r\n/g, "\n"));
    hash.update("\0");
  }
  return hash.digest("hex");
}

/** The hash a bundle's header records, or null when the file is missing or has no marker. */
export function readBundleHash(file = BUNDLE_PATH) {
  let head;
  try {
    head = fs.readFileSync(file, "utf8").split("\n", 4);
  } catch {
    return null;
  }
  const line = head.find((l) => l.startsWith(HASH_MARKER));
  return line ? line.slice(HASH_MARKER.length).trim() : null;
}

async function main() {
  const esbuild = await import("esbuild");
  const hash = hashA2uiSources();
  fs.mkdirSync(path.dirname(BUNDLE_PATH), { recursive: true });
  await esbuild.build({
    entryPoints: [path.join(SOURCES_DIR, "cli.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node24",
    outfile: BUNDLE_PATH,
    minify: false,
    legalComments: "none",
    logLevel: "info",
    banner: {
      js: [
        "#!/usr/bin/env node",
        `${HASH_MARKER}${hash}`,
        "// Generated by scripts/build-a2ui-check.mjs (pnpm build:a2ui-check) from packages/core/src/a2ui/*.ts. Do not edit; rebuild.",
      ].join("\n"),
    },
  });
  console.log(
    `a2ui checker bundled to ${path.relative(ROOT, BUNDLE_PATH)} (sources ${hash.slice(0, 12)})`,
  );
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
