#!/usr/bin/env node
/**
 * Fetches the official Cubism SDK for Web into `ui/vendor/cubism/`, where `ui/figure.js`
 * resolves it. Nothing the script puts there is committed: the SDK's Core is Live2D's
 * proprietary build and its Framework lives under the Live2D Open Software License — both
 * travel under their own terms, from the official download, on the operator's machine.
 *
 * The archive is pinned: the URL below names one release, and its SHA-256 is checked
 * before anything is unpacked, so what runs here is the release the adapter was written
 * against and not whatever the CDN serves that day. A version bump is a new line here AND
 * a pass of the adapter's checks (docs in the README), not a silent float.
 *
 * `--check` verifies without downloading (CI): the vendor tree must already be there and
 * hash-clean, or the step fails.
 */
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

/** One pinned release of the Cubism SDK for Web. Bump with care, per the header. */
const PIN = {
  // Live2D's download page serves this as `CubismSdkForWeb-5-r.5.zip`; the URL is what the
  // page's button resolved to when this pin was written (the CDN keeps old versions).
  url: "https://cubism.live2d.com/sdk-web/bin/CubismSdkForWeb-5-r.5.zip",
  sha256: "", // filled by --pin (below); empty means the pin is not yet recorded
};

const here = path.dirname(fileURLToPath(import.meta.url));
const vendor = path.resolve(here, "..", "ui", "vendor");

const mode = process.argv[2] ?? "fetch";

if (mode === "--pin") {
  // Record a pin: download, hash, rewrite this script's PIN block. One command per bump.
  const tmp = path.join(vendor, "sdk.zip");
  await mkdir(vendor, { recursive: true });
  execFileSync("curl", ["-fSL", "-o", tmp, PIN.url], { stdio: "inherit" });
  const bytes = await readFile(tmp);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const source = await readFile(new URL(import.meta.url), "utf8");
  await writeFile(
    new URL(import.meta.url),
    source.replace('sha256: "", // filled by --pin', `sha256: "${sha256}", // recorded by --pin`),
  );
  console.log(`pinned: ${sha256}`);
  process.exit(0);
}

if (mode === "--check") {
  const marker = path.join(vendor, "cubism", ".pinned-sha256");
  if (!existsSync(marker)) {
    console.error("vendor/cubism is absent — run `node scripts/fetch-cubism.mjs` first");
    process.exit(1);
  }
  const recorded = (await readFile(marker, "utf8")).trim();
  if (PIN.sha256 !== "" && recorded !== PIN.sha256) {
    console.error(`vendor is ${recorded}, the pin says ${PIN.sha256} — refetch`);
    process.exit(1);
  }
  console.log(`vendor ok (${recorded || "unpinned local"})`);
  process.exit(0);
}

// fetch (default)
if (PIN.sha256 === "") {
  console.error("the pin carries no sha256 — run `node scripts/fetch-cubism.mjs --pin` first");
  process.exit(1);
}

await rm(vendor, { recursive: true, force: true });
await mkdir(vendor, { recursive: true });
const tmp = path.join(vendor, "sdk.zip");
execFileSync("curl", ["-fSL", "-o", tmp, PIN.url], { stdio: "inherit" });

const bytes = await readFile(tmp);
const sha256 = createHash("sha256").update(bytes).digest("hex");
if (sha256 !== PIN.sha256) {
  console.error(`the archive is ${sha256}, the pin says ${PIN.sha256} — refusing to unpack`);
  process.exit(1);
}

// Unzip with the system tool (no dependency to carry): the SDK's zip holds Framework/, Core/
// and Shaders/ beside a Samples tree this adapter does not use and is not unpacked.
execFileSync("unzip", ["-q", tmp, "-d", path.join(vendor, "sdk")], { stdio: "inherit" });

// The adapter imports `./vendor/cubism/entry.js` — the Framework's public surface, re-exported
// from the unpacked tree so a version bump touches this script and nothing else.
const sdkRoot = path.join(vendor, "sdk", "CubismSdkForWeb-5-r.5");
const entry = `/**
 * Generated by scripts/fetch-cubism.mjs: the adapter's view of the SDK, from the unpacked
 * release. Regenerated, not edited — a version bump rewrites this file.
 */
export { CubismFramework } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/live2dcubismframework.js";
export { CubismModel } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/model/cubismmodel.js";
export { CubismModelSettingJson } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/cubismmodelsettingjson.js";
export { CubismMatrix44 } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/math/cubismmatrix44.js";
export { CubismEyeBlink } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/effect/cubismeyeblink.js";
export { CubismExpressionMotionManager } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/motion/cubismexpressionmotionmanager.js";
export { CubismShaderManager_WebGL } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/rendering/cubismshader_webgl.js";
export { CubismMotionManager } from "../../sdk/CubismSdkForWeb-5-r.5/Framework/src/motion/cubismmotionmanager.js";
`;
await writeFile(path.join(vendor, "cubism", "entry.js"), entry);
await writeFile(path.join(vendor, "cubism", ".pinned-sha256"), `${sha256}\n`);
await rm(tmp, { force: true });

console.log(`cubism sdk fetched and pinned: ${sha256}`);
console.log("The Core's licence (Live2D Proprietary Software License) and the Framework's");
console.log("(Live2D Open Software License) travel with the unpacked tree — keep them there.");
