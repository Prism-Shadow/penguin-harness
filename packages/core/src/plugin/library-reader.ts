/**
 * PenguinHarness plugin library: reads what each plugin package carries for an Agent (part of
 * core — hooks, skills and their loading and installing into Agent State all live in one SDK).
 *
 * A plugin package declares its content as contributions of its module (./library.ts), which its
 * build writes into `ifaces.json`; the library reads that table (./table.ts, ./contributions.ts),
 * the npm fields of its `package.json` (./package-json.ts), and the files the contributions name:
 * each Skill's directory, the hook package's scripts, each Workbench app's sources. Its icon is
 * the SVG its card names, else `icon.svg` at the package root; its README is `README.md` there.
 * Nothing in a package is installed by convention, and nothing in it is run.
 *
 * The files are the runtime source of truth — read and parsed on every call, no caching (files
 * are small, calls are infrequent) — so editing a SKILL.md or a hook script takes effect at
 * once; editing a declaration takes the package's build. The shipped plugins are committed
 * content reached through declared dependencies (./library-host.ts), so one that fails to load —
 * or whose package reads with a warning — is a broken install or a broken plugin and throws with
 * the path, never a silently smaller library. Install / uninstall / scan live in core's state
 * layer, which gets the same LibraryPlugin from here whatever the package was declared with.
 *
 * Besides the packages this build ships, the library lists what the operator installed on the
 * server: the packages of the data root's plugin prefix (useInstalledPluginPrefix) whose table
 * contributes Skills, a hook package, MCP servers or Workbench apps. Those are the operator's,
 * not the build's, so they are read leniently: one that will not read is left out with a
 * warning instead of failing the library, a field that will not read is missing with a warning,
 * and a skill without a dated version reads as unversioned.
 *
 * Docs: packages/docs/content/skills.{zh,en}.md (site path /docs/skills) documents the plugin
 * format, the versions and the built-in library.
 */
import fs from "node:fs";
import path from "node:path";
import { formatFrontmatter } from "@prismshadow/skills";
import { collectVaultRefs, resolveMCPServer } from "../environment/mcp/config.js";
import type { HookCommand, QuickStart } from "./library.js";
import { libraryContributions } from "./contributions.js";
import type { LibraryContributions, PluginMcpServer } from "./contributions.js";
import { readPluginIcon } from "./icon.js";
import { libraryRoots, warnOnce } from "./library-host.js";
import type { LibraryRoot } from "./library-host.js";
import { PLUGIN_NAME_PATTERN, PLUGIN_VERSION_PATTERN, readPackageJson } from "./package-json.js";
import { parseSkillFrontmatter } from "./skill-frontmatter.js";
import type { SkillMetadata } from "./skill-frontmatter.js";
import { readPluginTable } from "./table.js";

/** A skill in the library: metadata + full SKILL.md content (including frontmatter, written as-is on install). */
export interface LibrarySkill extends SkillMetadata {
  content: string;
  /** The plugin's raw `icon.svg`, stamped onto every skill by the loader — a skill has no icon of its own — and written as `icon.svg` beside SKILL.md on install, so the installed copy carries it; absent when the plugin ships none. */
  icon?: string;
  /**
   * Optional auxiliary files the SKILL.md references (e.g. `reference/API.md`), keyed by
   * POSIX-relative path within the skill directory; every entry except the top-level SKILL.md
   * (its own field) and a top-level icon.svg (reserved: the plugin's icon is what installs
   * there). Written alongside SKILL.md on install (subdirectories preserved). Read as UTF-8
   * text: a file that is not valid UTF-8 (an image) is left out, never installed garbled. The
   * field is omitted when a skill has no extra files.
   */
  files?: Record<string, string>;
}

/**
 * The manifest an installed hook package carries (`agent_state/hooks/<plugin>/hooks.json`),
 * generated by the installer from the plugin's `hooks` contribution: identity and display fields
 * plus one script list per hook point (`stop`, `pre_tool_use`, `user_prompt`). Whether a
 * Session runs hooks at all is an Agent-level decision (`hooks.enabled` in system_config.yaml),
 * not a per-package one. The plugin's icon is not part of it: the installer writes `icon.svg`
 * beside the manifest instead. Unknown keys are ignored rather than rejected.
 */
export interface HookManifest {
  name: string;
  description: string;
  description_zh?: string;
  /** The package's own version, `YYYY.MM.DD.N` — a library plugin's hooks contribution `version` (an installed copy may carry the legacy `YYYY-MM-DD.N`, a hand-written one anything). */
  version: string;
  /** Stop commands, consulted after every Task of a run. */
  stop: HookCommand[];
  /** Pre-tool-use commands, consulted before each tool call's approval. */
  pre_tool_use: HookCommand[];
  /** User-prompt expansion commands: run on every Prompt the user submits, or — `trigger: "host"` — only when the host starts the flow the package owns (goal mode's start). */
  user_prompt: HookCommand[];
}

/** A plugin's hook package as read from the library: the manifest to install and its directory's files (relative path → text). */
export interface LibraryHooks {
  manifest: HookManifest;
  files: Record<string, string>;
}

/** A workbench package copied into an Agent; its dated version lives in its own package.json penguin.version. */
export interface LibraryWorkbench {
  name: string;
  version: string;
  files: Record<string, string>;
}

/** A plugin in the library: its npm fields, its card, and the content it ships. */
export interface LibraryPlugin {
  /** Plugin name: its package name without the scope (`a2ui` for `@penguinharness/a2ui`). */
  name: string;
  /** The npm package the plugin is, e.g. `@penguinharness/a2ui`. */
  packageName: string;
  /** `installed` for a package the operator installed on the server (see useInstalledPluginPrefix); absent for one this build ships. */
  source?: "installed";
  /** Display name (the card's `title`, optional); the UI shows the plugin name without it. */
  title?: string;
  titleZh?: string;
  /** English one-line description (package.json `description`); "" when the package carries none — every shipped plugin does. */
  description: string;
  /** Chinese description (the card's `descriptionZh`, optional). */
  descriptionZh?: string;
  /** UI short descriptions (the card's `shortDescription(Zh)`, optional). */
  shortDescription?: string;
  shortDescriptionZh?: string;
  /**
   * The plugin's npm version: `package.json`'s `version` (it follows the release). What an
   * installed copy is compared against is not this but the dated version of each part — every
   * skill's, and the hook package's (see pluginContentVersion).
   */
  version: string;
  /** Category id (the card's `category`, see PLUGIN_CATEGORIES); absent or unknown → the "other" group. */
  category?: string;
  /** Whether default_agent gets this plugin at creation (the card's `preinstall`, default true; always false for an installed package — the operator chose it for the server, not for every new Project). */
  preinstall: boolean;
  /** The package's npm `author`, `homepage`, `repository` URL and `license`, for the detail dialog (each optional). */
  author?: string;
  homepage?: string;
  repository?: string;
  license?: string;
  /** Raw SVG of the plugin's icon (see readPluginIcon) — every built-in plugin ships one. It is the icon of everything the plugin ships: stamped onto each skill and written beside an installed hook package. */
  icon?: string;
  skills: LibrarySkill[];
  workbenches?: LibraryWorkbench[];
  hooks?: LibraryHooks;
  /** The MCP servers the plugin contributes, each with its full list of setup keys; [] when none. */
  mcpServers: PluginMcpServer[];
  /** The demo the Plugins page's quick start pre-fills (the card's `quickStart`, optional). */
  quickStart?: QuickStart;
}

/** Reads one root: a shipped plugin that will not read throws; an installed one is left out (null) with a warning. */
function readRoot(name: string, root: LibraryRoot): LibraryPlugin | null {
  if (!root.installed) return readPluginDir(name, root);
  try {
    return readPluginDir(name, root);
  } catch (err) {
    warnOnce(
      `[plugins] ${root.packageName} is installed but not listed: ${err instanceof Error ? err.message : String(err)}`,
    );
    return null;
  }
}

/**
 * Decodes bytes as UTF-8, or null when they are not valid UTF-8 (an image, an archive). A
 * byte-order mark stays in the text (`ignoreBOM`), so a text file installs byte for byte.
 */
const strictUtf8 = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });
function utf8Text(bytes: Uint8Array): string | null {
  try {
    return strictUtf8.decode(bytes);
  } catch {
    return null;
  }
}

/**
 * Recursively collects a directory's files as text keyed by POSIX-relative path, skipping the
 * names in `except` at the top level. Symlinks and other non-regular entries are skipped, and so
 * is a file that is not valid UTF-8 — what installs is text, and a binary file read as text
 * would install garbled; each one left out is pushed to `skipped` (the path under `dir`).
 * Returns undefined when the directory has no such files.
 */
function readDirFiles(
  dir: string,
  except: readonly string[],
  skipped: string[],
): Record<string, string> | undefined {
  const files: Record<string, string> = {};
  const walk = (abs: string, rel: string): void => {
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
      const childRel = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        walk(path.join(abs, entry.name), childRel);
      } else if (entry.isFile()) {
        if (rel === "" && except.includes(entry.name)) continue;
        const text = utf8Text(fs.readFileSync(path.join(abs, entry.name)));
        if (text === null) skipped.push(childRel);
        else files[childRel] = text;
      }
    }
  };
  walk(dir, "");
  return Object.keys(files).length > 0 ? files : undefined;
}

/** Whether `dir` is a directory (not a symlink to one). */
function isDirectory(dir: string): boolean {
  try {
    return fs.lstatSync(dir).isDirectory();
  } catch {
    return false;
  }
}

/**
 * Reads one skill directory: name from the contribution (overriding frontmatter), SKILL.md
 * verbatim, and every other file as auxiliary content. The icon is not read here: a skill has
 * none of its own, and stampSkill gives it the plugin's. A shipped skill must carry its own dated
 * `version` in the current spelling — it is what an installed copy is compared against; an
 * installed package's skill without one reads as unversioned (""), older than any real version
 * and never flagged behind.
 */
function readSkillDir(
  dir: string,
  rel: string,
  name: string,
  strict: boolean,
  skipped: string[],
): LibrarySkill {
  const file = path.join(dir, "SKILL.md");
  const content = fs.readFileSync(file, "utf8");
  const meta = parseSkillFrontmatter(content);
  if (!meta) throw new Error(`Library skill ${file} has no frontmatter with a name`);
  if (strict && !PLUGIN_VERSION_PATTERN.test(meta.version)) {
    throw new Error(`Library skill ${file}: version must be YYYY.MM.DD.N`);
  }
  const auxiliary: string[] = [];
  const files = readDirFiles(dir, ["SKILL.md", "icon.svg"], auxiliary);
  skipped.push(...auxiliary.map((file) => `${rel}/${file}`));
  return { ...meta, name, content, ...(files !== undefined ? { files } : {}) };
}

/**
 * Resolves a library skill against its plugin: the plugin's UI short descriptions are the
 * skill's, its icon becomes the skill's, and the installable `content` gets the full frontmatter
 * regenerated in canonical field order, carrying the skill's own `version` (none for an
 * unversioned one) — the installed copy is self-describing (update checks read its `version`,
 * the UI its short descriptions and icon) the same way an installed hook package's hooks.json is
 * generated.
 */
function stampSkill(
  skill: LibrarySkill,
  plugin: {
    shortDescription?: string;
    shortDescriptionZh?: string;
    icon?: string;
  },
): LibrarySkill {
  const { shortDescription, shortDescriptionZh } = plugin;
  const front = formatFrontmatter([
    ["name", skill.name],
    ["description", skill.description],
    ["short_description", shortDescription],
    ["short_description_zh", shortDescriptionZh],
    ["version", skill.version !== "" ? skill.version : undefined],
  ]);
  const body = skill.content.replace(/^﻿?---\r?\n[\s\S]*?\r?\n---/, "");
  return {
    ...skill,
    ...(shortDescription !== undefined ? { shortDescription } : {}),
    ...(shortDescriptionZh !== undefined ? { shortDescriptionZh } : {}),
    ...(plugin.icon !== undefined ? { icon: plugin.icon } : {}),
    content: `${front}${body}`,
  };
}

/** The directories directly under `<dir>/<parent>/` (none when it is not there). */
function subdirectories(dir: string, parent: string): string[] {
  const at = path.join(dir, parent);
  if (!isDirectory(at)) return [];
  return fs
    .readdirSync(at, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => `${parent}/${entry.name}`);
}

/** The declared skills, read from the directories they name; a directory under `skills/` that no entry names is said and left out. */
function readSkills(
  dir: string,
  declared: LibraryContributions["skills"],
  strict: boolean,
  warnings: string[],
  skipped: string[],
): LibrarySkill[] {
  const skills: LibrarySkill[] = [];
  for (const { name, path: rel } of declared) {
    const skillDir = path.join(dir, ...rel.split("/"));
    if (!fs.existsSync(path.join(skillDir, "SKILL.md"))) {
      warnings.push(`the skill "${name}" names ${rel}, which holds no SKILL.md; it is not listed`);
      continue;
    }
    skills.push(readSkillDir(skillDir, rel, name, strict, skipped));
  }
  for (const rel of subdirectories(dir, "skills")) {
    if (!declared.some((skill) => skill.path === rel)) {
      warnings.push(`${rel} is not declared by a skills contribution; it is not installed`);
    }
  }
  return skills.sort((a, b) => a.name.localeCompare(b.name));
}

/** The declared Workbench apps: each one's source files, its own package.json carrying its dated version and modules. */
function readWorkbenches(
  dir: string,
  declared: LibraryContributions["workbenches"],
  warnings: string[],
  skipped: string[],
): LibraryWorkbench[] {
  const workbenches: LibraryWorkbench[] = [];
  for (const { name, path: rel } of declared) {
    try {
      const appDir = path.join(dir, ...rel.split("/"));
      if (!isDirectory(appDir)) throw new Error("the directory does not exist");
      const files = readDirFiles(appDir, [], skipped) ?? {};
      if (
        Object.keys(files).some(
          (file) =>
            file === "state.json" ||
            file.split("/").some((part) => part.startsWith(".") || part === "node_modules"),
        )
      )
        throw new Error("ship source files only, without state.json, dot files or node_modules");
      const pkg = JSON.parse(files["package.json"] ?? "{}");
      const version = pkg.penguin?.version;
      if (typeof version !== "string" || !PLUGIN_VERSION_PATTERN.test(version))
        throw new Error("package.json penguin.version must be YYYY.MM.DD.N");
      if (!Array.isArray(pkg.penguin?.modules) || pkg.penguin.modules.length === 0)
        throw new Error("package.json must declare penguin.modules");
      workbenches.push({ name, version, files });
    } catch (error) {
      warnings.push(`${rel}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  for (const rel of subdirectories(dir, "workbenches")) {
    if (!declared.some((workbench) => workbench.path === rel)) {
      warnings.push(`${rel} is not declared by a workbenches contribution; it is not installed`);
    }
  }
  return workbenches;
}

/**
 * Reads one plugin package: its npm fields, its table's contributions, and the files they name.
 * What the field readers warn about, the loader adds to: a package with no table (never built), a
 * declared directory that is not there, a directory under `skills/` or `workbenches/` nothing
 * declares, a `hooks/` directory without a hooks contribution, a quick start naming skills the
 * package does not ship (those names are dropped), an icon that will not do, a file left out of a
 * skill for not being text, an MCP server whose config the server resolver refuses (left out; its
 * references are checked as written, so one in the server's address is a fault), a setup key its
 * server's config never references (dropped). A shipped plugin must read clean, so for one of
 * those any warning throws; an installed package lists with the field missing, and the warning
 * goes to the log.
 */
function readPluginDir(name: string, root: LibraryRoot): LibraryPlugin {
  const { dir } = root;
  const strict = !root.installed;
  const { manifest, warnings } = readPackageJson(dir);
  const table = readPluginTable(dir);
  if (table === null) {
    throw new Error(
      `${dir} has no ifaces.json: build the package (its build runs penguin-gen-ifaces)`,
    );
  }
  const contributions = libraryContributions(table, warnings);
  const card = contributions.card ?? {};
  const skipped: string[] = [];
  const skills = readSkills(dir, contributions.skills, strict, warnings, skipped);
  const workbenches = readWorkbenches(dir, contributions.workbenches, warnings, skipped);
  const { icon, warnings: iconWarnings } = readPluginIcon(dir, card.icon);
  warnings.push(...iconWarnings);
  let hooks: LibraryHooks | undefined;
  const declaredHooks = contributions.hooks;
  if (declaredHooks !== undefined) {
    const hooksDir = path.join(dir, ...declaredHooks.path.split("/"));
    const files = isDirectory(hooksDir) ? readDirFiles(hooksDir, [], skipped) : undefined;
    if (files === undefined) {
      warnings.push(
        `the hook package names ${declaredHooks.path}, which holds no files; the hook package is not listed`,
      );
    } else {
      hooks = {
        manifest: {
          name,
          description: manifest.description,
          ...(card.descriptionZh !== undefined ? { description_zh: card.descriptionZh } : {}),
          // The package's own dated version: what an installed hooks.json is compared against.
          version: declaredHooks.version,
          stop: declaredHooks.stop,
          pre_tool_use: declaredHooks.pre_tool_use,
          user_prompt: declaredHooks.user_prompt,
        },
        files,
      };
    }
  } else if (isDirectory(path.join(dir, "hooks"))) {
    warnings.push("hooks/ is not declared by a hooks contribution; it is not installed");
  }
  for (const rel of skipped) warnings.push(`${rel} is not a text file; it is not installed`);
  const mcpServers = readMcpServerEntries(contributions.mcpServers, warnings);
  let quickStart = card.quickStart;
  if (quickStart?.skills !== undefined) {
    const unknown = quickStart.skills.filter((n) => !skills.some((s) => s.name === n));
    if (unknown.length > 0) {
      warnings.push(
        `the card's quickStart.skills names skills the package does not ship (${unknown.join(", ")}); ignored`,
      );
      const { skills: _named, ...rest } = quickStart;
      const known = quickStart.skills.filter((n) => !unknown.includes(n));
      quickStart = known.length > 0 ? { ...rest, skills: known } : rest;
    }
  }
  if (warnings.length > 0) {
    if (strict) throw new Error(`${dir}: ${warnings.join("; ")}`);
    for (const warning of warnings) warnOnce(`[plugins] ${root.packageName}: ${warning}`);
  }
  const { shortDescription, shortDescriptionZh, descriptionZh } = card;
  return {
    name,
    packageName: root.packageName,
    ...(root.installed ? { source: "installed" as const } : {}),
    ...(card.title !== undefined ? { title: card.title } : {}),
    ...(card.titleZh !== undefined ? { titleZh: card.titleZh } : {}),
    description: manifest.description,
    ...(descriptionZh !== undefined ? { descriptionZh } : {}),
    ...(shortDescription !== undefined ? { shortDescription } : {}),
    ...(shortDescriptionZh !== undefined ? { shortDescriptionZh } : {}),
    version: manifest.version,
    ...(card.category !== undefined ? { category: card.category } : {}),
    preinstall: !root.installed && card.preinstall !== false,
    ...(manifest.author !== undefined ? { author: manifest.author } : {}),
    ...(manifest.homepage !== undefined ? { homepage: manifest.homepage } : {}),
    ...(manifest.repository !== undefined ? { repository: manifest.repository } : {}),
    ...(manifest.license !== undefined ? { license: manifest.license } : {}),
    ...(icon !== undefined ? { icon } : {}),
    skills: skills.map((skill) =>
      stampSkill(skill, {
        ...(shortDescription !== undefined ? { shortDescription } : {}),
        ...(shortDescriptionZh !== undefined ? { shortDescriptionZh } : {}),
        ...(icon !== undefined ? { icon } : {}),
      }),
    ),
    ...(hooks !== undefined ? { hooks } : {}),
    ...(workbenches.length > 0 ? { workbenches } : {}),
    mcpServers,
    ...(quickStart !== undefined ? { quickStart } : {}),
  };
}

/**
 * A package's MCP servers as the library lists them: each one the server resolver accepts with
 * its references as written, its setup keys completed with every `${KEY}` its config references
 * (declared ones first, in their order), a declared key nothing references dropped.
 */
function readMcpServerEntries(declared: PluginMcpServer[], warnings: string[]): PluginMcpServer[] {
  const servers: PluginMcpServer[] = [];
  for (const server of declared) {
    try {
      resolveMCPServer({ name: server.name, config: server.config });
    } catch (err) {
      warnings.push(
        `the MCP server "${server.name}": ${err instanceof Error ? err.message : String(err)}; it is not listed`,
      );
      continue;
    }
    const refs = collectVaultRefs(server.config);
    const setup = server.setup.filter((item) => {
      if (refs.includes(item.key)) return true;
      warnings.push(
        `the MCP server "${server.name}" lists setup key ${item.key}, which its config never references; ignored`,
      );
      return false;
    });
    for (const key of refs) if (!setup.some((item) => item.key === key)) setup.push({ key });
    servers.push({ ...server, setup });
  }
  return servers;
}

/** Reads every plugin in the library (one per plugin package: the shipped ones, see ./library-host.ts, and the installed ones, see useInstalledPluginPrefix), sorted by name. */
export function loadLibraryPlugins(): LibraryPlugin[] {
  return [...libraryRoots()]
    .map(([name, root]) => readRoot(name, root))
    .filter((plugin): plugin is LibraryPlugin => plugin !== null)
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** The plugins default_agent installs at initialization: every library plugin except those whose card sets `preinstall: false`. */
export function loadPreinstalledPlugins(): LibraryPlugin[] {
  return loadLibraryPlugins().filter((plugin) => plugin.preinstall);
}

/** Reads a single library plugin by name; undefined when the library has no such plugin (names are looked up, never joined into a path). */
export function libraryPlugin(name: string): LibraryPlugin | undefined {
  const root = libraryRoots().get(name);
  return root !== undefined ? (readRoot(name, root) ?? undefined) : undefined;
}

/**
 * Where a library plugin's package is on this machine, with its npm name and version — what an
 * export zips. Undefined when the library has no such plugin.
 */
export function libraryPluginPackage(
  name: string,
): { dir: string; packageName: string; version: string } | undefined {
  const root = libraryRoots().get(name);
  if (root === undefined) return undefined;
  const { version } = readPackageJson(root.dir).manifest;
  return { dir: root.dir, packageName: root.packageName, version };
}

/**
 * Reads a package directory as the library would read it once installed — the check an
 * uploaded or a local package passes before anything is installed. Throws, naming the file, on
 * what the library would refuse: a package.json without a valid npm name or a release version
 * (PluginManifestError), a name whose unscoped part is not a plugin name, a package with no
 * `ifaces.json` (never built) or one that will not read, a skill without a SKILL.md frontmatter
 * naming it. Whatever reads with a warning instead (see readPluginDir) is logged, and the package
 * reads with that field missing.
 */
export function readLibraryPackage(dir: string): LibraryPlugin {
  const { manifest } = readPackageJson(dir);
  return readPluginDir(manifest.pluginName, {
    dir,
    packageName: manifest.name,
    installed: true,
  });
}

/**
 * The README.md at a library plugin's package root, as npm ships it: undefined when the
 * library has no such plugin, null when the package has no readme. Read on request rather than
 * with the listing — a readme is long and wanted only for the plugin someone opened.
 */
export function libraryPluginReadme(name: string): string | null | undefined {
  const root = libraryRoots().get(name);
  if (root === undefined) return undefined;
  try {
    return fs.readFileSync(path.join(root.dir, "README.md"), "utf8");
  } catch {
    return null;
  }
}

/** Finds a library skill by its own name (across every plugin), with the plugin that ships it. */
export function librarySkill(
  name: string,
): { plugin: LibraryPlugin; skill: LibrarySkill } | undefined {
  for (const plugin of loadLibraryPlugins()) {
    const skill = plugin.skills.find((s) => s.name === name);
    if (skill) return { plugin, skill };
  }
  return undefined;
}

/**
 * What a package on this machine says about itself for a card — the display fields of its card
 * contribution and its icon — for a package the library does not list (a server module). A
 * package without a table, or one whose table will not read, has no card fields; its icon is still
 * `icon.svg` at its root when that is a safe one, as for every package. A field that will not
 * read is missing.
 */
export function readPackageCard(dir: string): {
  card: NonNullable<LibraryContributions["card"]>;
  icon?: string;
} {
  let table: ReturnType<typeof readPluginTable>;
  try {
    table = readPluginTable(dir);
  } catch {
    table = null;
  }
  const card = (table === null ? undefined : libraryContributions(table, []).card) ?? {};
  const { icon } = readPluginIcon(dir, card.icon);
  return { card, ...(icon !== undefined ? { icon } : {}) };
}
