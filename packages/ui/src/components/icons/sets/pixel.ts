/** Path data per grid, built on first use and keyed by the grid array the tables hold. */
const PATHS = new WeakMap<PixelGrid, string>();

/**
 * A grid as SVG path data in its own 16x16 user space: each horizontal run of ink cells in a row
 * becomes one closed rectangle `M{x} {y}h{n}v1h-{n}z`, so a figure is as few subpaths as its rows
 * have runs. Paint it with `shape-rendering="crispEdges"` and no stroke.
 */
export function pixelPath(grid: PixelGrid): string {
  const cached = PATHS.get(grid);
  if (cached !== undefined) return cached;
  let d = "";
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === "#") x += 1;
      const n = x - start;
      d += `M${start} ${y}h${n}v1h-${n}z`;
    }
  });
  PATHS.set(grid, d);
  return d;
}
