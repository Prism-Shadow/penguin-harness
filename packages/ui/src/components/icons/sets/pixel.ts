/**
 * The pixel set: every registry glyph and every mark redrawn on a 16x16 grid of whole cells,
 * painted square in the ink colour with crisp edges. Each grid is sixteen strings of sixteen
 * characters, `#` for ink and `.` for empty, one row per line so the drawing reads in source;
 * `pixelPath` turns it into one path of unit squares.
 *
 * The rules that keep the set one family:
 * - A drawing stays inside the 14x14 live area (rows and columns 1-14). It touches the outer
 *   ring only where its silhouette needs the full width.
 * - Every stroke is one cell wide. A diagonal is a stair of single cells, never doubled into a
 *   two-cell band, and a round shape is a circle with its corners cut, not a square.
 * - A recurring detail is drawn once: the 13-cell status circle (centred on cell 7,7) under
 *   every circled mark and clock, the smaller circles cut the same way, one arrowhead (a tip and
 *   three cells a side) on every arrow, one chevron (a tip and four), one page with its fold,
 *   one tray, one window frame, one shield, one keyboard plate, one set of sun rays.
 * - A small solid dot (an eye, a lamp, a key) is a single cell; only the ellipsis, the whole of
 *   its mark, uses two by two.
 *
 * One cell is one CSS pixel. A cell that lands between device pixels is smeared over two by
 * antialiasing and the drawing goes soft, which is the opposite of the look, so the renderer
 * lays the grid out at exactly 16 CSS px whenever the box is 13 px or more (centred, spilling
 * past a smaller box) and only scales it below that. A detail finer than a cell does not exist
 * here: each mark is simplified to what a 16-pixel drawing can still say, keeping its identity.
 */
