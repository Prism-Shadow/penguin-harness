/**
 * The SQLite → PostgreSQL translator behind `PENGUIN_DB=pg`.
 *
 * The platform's data layer speaks node:sqlite: ~190 prepared statements, the schema script
 * and the ordered migrations. Rather than rewrite every call site to an async driver, the PG
 * backend translates each statement on its way to PostgreSQL. That translation is the part
 * that can be wrong without a database in sight — a quoted `?` counted as a parameter, an
 * `INSERT OR REPLACE` without its conflict target, a bare column under `GROUP BY` — so it is
 * pinned here, statement by statement, with no PostgreSQL required.
 *
 * The integration half (`db-pg.test.ts`) is the opposite: a real PostgreSQL, a real schema,
 * skipped unless `PENGUIN_TEST_PG_DSN` names one.
 */
import { describe, expect, it } from "vitest";
import {
  convertPlaceholders,
  splitStatements,
  translateScript,
  translateStatement,
} from "../src/db/pg/translate.js";

/** No catalog available: INSERT OR REPLACE tests pass the primary key explicitly. */
const noPk = { pkOf: () => null };
const withPk = (table: string, cols: string[]) => ({
  pkOf: (t: string) => (t === table ? cols : null),
});

describe("splitStatements", () => {
  it("splits on semicolons outside quotes and comments", () => {
    const script = [
      "CREATE TABLE a (x TEXT DEFAULT 'a;b');",
      "-- a comment; with a semicolon",
      "CREATE TABLE b (y TEXT); /* block; comment */",
      "CREATE INDEX c ON b(y)",
    ].join("\n");
    const parts = splitStatements(script);
    expect(parts).toHaveLength(3);
    expect(parts[0]).toContain("'a;b'");
    // a comment ahead of a statement travels with it
    expect(parts[1]).toContain("-- a comment; with a semicolon");
    expect(parts[1]).toContain("CREATE TABLE b (y TEXT)");
    expect(parts[2]).toContain("CREATE INDEX c ON b(y)");
  });
});

describe("convertPlaceholders", () => {
  it("numbers ? positionally, skipping literals and comments", () => {
    const { sql } = convertPlaceholders(
      "SELECT * FROM t WHERE a = ? AND b = 'not ? a param' -- ? in a comment\n AND c = ?",
    );
    expect(sql).toContain("a = $1");
    expect(sql).toContain("c = $2");
    expect(sql).toContain("'not ? a param'");
    expect(sql).toContain("-- ? in a comment");
  });

  it("gives a repeated :name ONE placeholder, in order of first appearance", () => {
    const { sql, named } = convertPlaceholders(
      "UPDATE t SET a = :a, b = :b, c = :a WHERE id = :id",
    );
    expect(named).toEqual(["a", "b", "id"]);
    expect(sql).toContain("a = $1");
    expect(sql).toContain("b = $2");
    expect(sql).toContain("c = $1");
    expect(sql).toContain("id = $3");
  });

  it("leaves a ::cast alone", () => {
    const { sql, named } = convertPlaceholders("SELECT x::text FROM t WHERE id = :id");
    expect(named).toEqual(["id"]);
    expect(sql).toContain("x::text");
    expect(sql).toContain("id = $1");
  });
});

describe("translateStatement: the mechanical rewrites", () => {
  it("drops the PRAGMAs PostgreSQL does not need", () => {
    for (const pragma of [
      "PRAGMA journal_mode = WAL;",
      "PRAGMA foreign_keys = ON;",
      "PRAGMA busy_timeout = 5000;",
      "PRAGMA synchronous = NORMAL;",
    ]) {
      expect(translateStatement(pragma, noPk)).toBeNull();
    }
  });

  it("turns BEGIN IMMEDIATE into a plain BEGIN", () => {
    expect(translateStatement("BEGIN IMMEDIATE", noPk)).toBe("BEGIN");
  });

  it("adds IF NOT EXISTS to ADD COLUMN", () => {
    expect(translateStatement("ALTER TABLE sessions ADD COLUMN sandbox TEXT", noPk)).toBe(
      "ALTER TABLE sessions ADD COLUMN IF NOT EXISTS sandbox TEXT",
    );
    // idempotent already: left alone
    expect(
      translateStatement("ALTER TABLE sessions ADD COLUMN IF NOT EXISTS sandbox TEXT", noPk),
    ).toBe("ALTER TABLE sessions ADD COLUMN IF NOT EXISTS sandbox TEXT");
  });

  it("turns AUTOINCREMENT into an identity column", () => {
    const sql = translateStatement(
      "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT)",
      noPk,
    );
    expect(sql).toContain("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
    expect(sql).not.toContain("AUTOINCREMENT");
  });
});

describe("translateStatement: INSERT OR REPLACE / OR IGNORE", () => {
  it("rewrites OR IGNORE to ON CONFLICT DO NOTHING", () => {
    const sql = translateStatement(
      "INSERT OR IGNORE INTO settings (key, value) VALUES (?, ?)",
      noPk,
    );
    expect(sql).toBe("INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT DO NOTHING");
  });

  it("rewrites OR REPLACE to ON CONFLICT (pk) DO UPDATE over the non-key columns", () => {
    const sql = translateStatement(
      "INSERT OR REPLACE INTO server_settings (key, value, updated_at) VALUES (?, ?, ?)",
      withPk("server_settings", ["key"]),
    );
    expect(sql).toBe(
      "INSERT INTO server_settings (key, value, updated_at) VALUES ($1, $2, $3) " +
        "ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = EXCLUDED.updated_at",
    );
  });

  it("falls back to DO NOTHING when the row is all key", () => {
    const sql = translateStatement("INSERT OR REPLACE INTO t (a) VALUES (?)", withPk("t", ["a"]));
    expect(sql).toContain("ON CONFLICT (a) DO NOTHING");
  });

  it("refuses to guess when no primary key is known", () => {
    expect(() => translateStatement("INSERT OR REPLACE INTO t (a, b) VALUES (?, ?)", noPk)).toThrow(
      /no primary key known/,
    );
  });
});

describe("translateStatement: PostgreSQL strictness the repos rely on", () => {
  it("qualifies bare SET-target references inside DO UPDATE", () => {
    // PG resolves an unqualified RHS column that shares a name with the SET target as
    // ambiguous; SQLite resolves it against the existing row.
    const sql = translateStatement(
      "INSERT INTO usage (project_id, requests) VALUES (?, ?) " +
        "ON CONFLICT (project_id) DO UPDATE SET requests = requests + :add",
      noPk,
    );
    expect(sql).toContain("SET requests = usage.requests + $3");
  });

  it("leaves excluded.* and function calls untouched", () => {
    const sql = translateStatement(
      "INSERT INTO t (a, b) VALUES (?, ?) " +
        "ON CONFLICT (a) DO UPDATE SET b = excluded.b || coalesce(b, '')",
      noPk,
    );
    expect(sql).toContain("excluded.b");
    expect(sql).toContain("coalesce(");
    expect(sql).not.toContain("t.coalesce");
  });

  it("maps SQLite's scalar MAX(a, b) to GREATEST, keeping the aggregate form", () => {
    expect(
      translateStatement(
        "SELECT MAX(COALESCE(last_active_at, ''), :at) FROM sessions WHERE session_id = :id",
        noPk,
      ),
    ).toContain("GREATEST(COALESCE(last_active_at, ''), $1)");
    // one argument is an aggregate and passes through
    expect(translateStatement("SELECT MAX(ts) FROM usage_records", noPk)).toContain("MAX(ts)");
  });

  it("maps value IS / IS NOT to IS [NOT] DISTINCT FROM, keeping NULL tests", () => {
    expect(translateStatement("SELECT * FROM t WHERE a IS 'x'", noPk)).toContain(
      "a IS NOT DISTINCT FROM 'x'",
    );
    expect(translateStatement("SELECT * FROM t WHERE a IS NOT 'x'", noPk)).toContain(
      "a IS DISTINCT FROM 'x'",
    );
    expect(translateStatement("SELECT * FROM t WHERE a IS NULL", noPk)).toContain("a IS NULL");
    expect(translateStatement("SELECT * FROM t WHERE a IS NOT NULL", noPk)).toContain(
      "a IS NOT NULL",
    );
  });

  it("makes LIKE case-insensitive again", () => {
    expect(translateStatement("SELECT * FROM t WHERE name LIKE ?", noPk)).toContain("ILIKE");
  });

  it("adds selected bare columns to GROUP BY", () => {
    const sql = translateStatement(
      "SELECT session_id, agent_id, count(*) AS n FROM sessions GROUP BY session_id ORDER BY n DESC",
      noPk,
    );
    expect(sql).toContain("GROUP BY session_id, agent_id");
  });

  it("leaves a query already grouping every bare column alone", () => {
    const before = "SELECT agent_id, count(*) FROM sessions GROUP BY agent_id";
    expect(translateStatement(before, noPk)).toContain("GROUP BY agent_id");
    expect(translateStatement(before, noPk)).not.toContain("agent_id, agent_id");
  });
});

describe("translateStatement: dates and times", () => {
  it("rewrites strftime bucketing onto to_char", () => {
    const sql = translateStatement(
      "SELECT strftime('%Y-%m-%dT%H:%M', ts, 'localtime') AS bucket, count(*) FROM usage_records GROUP BY bucket",
      noPk,
    );
    expect(sql).toContain("to_char(");
    expect(sql).not.toContain("strftime");
  });

  it("keeps date(column, :param) a TEXT date, as SQLite returns", () => {
    const sql = translateStatement("SELECT date(ts, :dayShift) AS d FROM usage_records", noPk);
    expect(sql).toContain("::date::text");
  });
});

describe("translateStatement: full-text search", () => {
  it("turns an FTS5 virtual table into a table with a tsvector column", () => {
    const sql = translateStatement(
      "CREATE VIRTUAL TABLE IF NOT EXISTS session_search USING fts5(" +
        "project_id UNINDEXED, session_id UNINDEXED, body, raw UNINDEXED)",
      noPk,
    );
    expect(sql).toContain("CREATE TABLE IF NOT EXISTS session_search");
    expect(sql).toContain("body_tsv tsvector");
    expect(sql).toContain("USING gin(body_tsv)");
    expect(sql).not.toContain("VIRTUAL TABLE");
  });

  it("rewrites MATCH and the bm25 rank column", () => {
    const sql = translateStatement(
      "SELECT raw, rank FROM session_search WHERE session_search MATCH ? ORDER BY rank LIMIT 10",
      noPk,
    );
    expect(sql).toContain("body_tsv @@ to_tsquery('simple', $1)");
    expect(sql).toContain("-ts_rank(body_tsv, to_tsquery('simple', $1))");
    expect(sql).not.toContain("MATCH");
  });
});

describe("translateScript", () => {
  it("translates every statement of a script and drops the no-ops", () => {
    const script = [
      "PRAGMA journal_mode = WAL;",
      "CREATE TABLE IF NOT EXISTS t (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT);",
      "CREATE INDEX IF NOT EXISTS idx_t_name ON t(name);",
    ].join("\n");
    const out = translateScript(script, noPk);
    expect(out).not.toContain("PRAGMA");
    expect(out).toContain("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
    expect(out).toContain("CREATE INDEX IF NOT EXISTS idx_t_name ON t(name)");
    // statements are still terminated, so the script runs as one exec()
    expect(out.trimEnd().endsWith(";")).toBe(true);
  });
});
