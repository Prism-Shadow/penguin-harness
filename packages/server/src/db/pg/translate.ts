/**
 * SQLite → PostgreSQL statement translation for the PG shim.
 *
 * The platform's SQL surface is finite and known (19 repos + migrations + schema);
 * this module rewrites the handful of SQLite-isms it uses into PostgreSQL, and
 * performs the mechanical placeholder conversion. Anything it does not recognise
 * passes through unchanged — PostgreSQL accepts the rest of what the repos write
 * (plain CRUD, CTEs, ON CONFLICT, RETURNING, aggregates).
 *
 * Translations performed:
 *  - `?` positional params            → `$1..$n` (literal/identifier/comment aware)
 *  - `:name` named params             → `$n` (order of first appearance)
 *  - INSERT OR REPLACE / OR IGNORE    → ON CONFLICT (pk) DO UPDATE / DO NOTHING
 *  - PRAGMA journal/foreign_keys/
 *    busy_timeout/synchronous         → no-op
 *  - PRAGMA user_version (get/set)    → _pg_meta table (handled by caller hooks)
 *  - PRAGMA table_info(t)             → information_schema query (caller hook)
 *  - BEGIN IMMEDIATE                  → BEGIN
 *  - ALTER TABLE ADD COLUMN           → ADD COLUMN IF NOT EXISTS
 *  - INTEGER PRIMARY KEY AUTOINCREMENT→ BIGINT GENERATED BY DEFAULT AS IDENTITY
 *  - strftime/date() bucketing exprs  → to_char / date_trunc equivalents
 */

/**
 * Timezone used where SQLite's 'localtime' modifier appears: the server's own zone,
 * like SQLite's, unless PENGUIN_PG_TZ names another.
 */
const LOCAL_TZ =
  process.env.PENGUIN_PG_TZ || Intl.DateTimeFormat().resolvedOptions().timeZone || "UTC";

/** Split a SQL script into statements on `;`, respecting quotes and comments. */
export function splitStatements(sql: string): string[] {
  const out: string[] = [];
  let cur = "";
  let i = 0;
  const n = sql.length;
  while (i < n) {
    const ch = sql[i];
    const next = sql[i + 1];
    // line comment
    if (ch === "-" && next === "-") {
      const end = sql.indexOf("\n", i);
      const stop = end === -1 ? n : end;
      cur += sql.slice(i, stop);
      i = stop;
      continue;
    }
    // block comment
    if (ch === "/" && next === "*") {
      const end = sql.indexOf("*/", i + 2);
      const stop = end === -1 ? n : end + 2;
      cur += sql.slice(i, stop);
      i = stop;
      continue;
    }
    // single-quoted string
    if (ch === "'") {
      let j = i + 1;
      while (j < n) {
        if (sql[j] === "'") {
          if (sql[j + 1] === "'") {
            j += 2;
            continue;
          }
          break;
        }
        j += 1;
      }
      cur += sql.slice(i, Math.min(j + 1, n));
      i = j + 1;
      continue;
    }
    // double-quoted identifier
    if (ch === '"') {
      let j = i + 1;
      while (j < n) {
        if (sql[j] === '"') {
          if (sql[j + 1] === '"') {
            j += 2;
            continue;
          }
          break;
        }
        j += 1;
      }
      cur += sql.slice(i, Math.min(j + 1, n));
      i = j + 1;
      continue;
    }
    if (ch === ";") {
      out.push(cur);
      cur = "";
      i += 1;
      continue;
    }
    cur += ch;
    i += 1;
  }
  if (cur.trim()) out.push(cur);
  return out.filter((s) => s.trim().length > 0);
}

/** Convert `?` and `:name` placeholders to `$n`. Returns the named-param order. */
export function convertPlaceholders(sql: string): { sql: string; named: string[] } {
  const named: string[] = [];
  const nameNum = new Map<string, number>();
  let out = "";
  let i = 0;
  const n = sql.length;
  let idx = 0;
  while (i < n) {
    const ch = sql[i];
    const next = sql[i + 1];
    if (ch === "-" && next === "-") {
      const end = sql.indexOf("\n", i);
      const stop = end === -1 ? n : end;
      out += sql.slice(i, stop);
      i = stop;
      continue;
    }
    if (ch === "/" && next === "*") {
      const end = sql.indexOf("*/", i + 2);
      const stop = end === -1 ? n : end + 2;
      out += sql.slice(i, stop);
      i = stop;
      continue;
    }
    if (ch === "'") {
      let j = i + 1;
      while (j < n) {
        if (sql[j] === "'") {
          if (sql[j + 1] === "'") {
            j += 2;
            continue;
          }
          break;
        }
        j += 1;
      }
      out += sql.slice(i, Math.min(j + 1, n));
      i = j + 1;
      continue;
    }
    if (ch === '"') {
      let j = i + 1;
      while (j < n) {
        if (sql[j] === '"') {
          if (sql[j + 1] === '"') {
            j += 2;
            continue;
          }
          break;
        }
        j += 1;
      }
      out += sql.slice(i, Math.min(j + 1, n));
      i = j + 1;
      continue;
    }
    if (ch === "?") {
      idx += 1;
      out += `$${idx}`;
      i += 1;
      continue;
    }
    // named param :name (not ::cast, not := )
    if (ch === ":" && next && /[A-Za-z_]/.test(next) && sql[i - 1] !== ":") {
      let j = i + 1;
      while (j < n && /[A-Za-z0-9_]/.test(sql[j] ?? "")) j += 1;
      const name = sql.slice(i + 1, j);
      // Same named param used N times → ONE placeholder ($n). Callers bind one
      // value per NAME (node:sqlite semantics), so per-occurrence numbering
      // produced "supplies 1 parameters, but prepared statement requires 3".
      let num = nameNum.get(name);
      if (num === undefined) {
        idx += 1;
        num = idx;
        nameNum.set(name, num);
        named.push(name);
      }
      out += `$${num}`;
      i = j;
      continue;
    }
    out += ch;
    i += 1;
  }
  return { sql: out, named };
}

/** Table + column names of a simple INSERT (used to build ON CONFLICT targets). */
function parseInsert(sql: string): { table: string; columns: string[] } | null {
  const m = sql.match(
    /INSERT\s+(?:OR\s+(?:REPLACE|IGNORE)\s+)?INTO\s+["']?([A-Za-z_][A-Za-z0-9_]*)["']?\s*\(([^)]*)\)/i,
  );
  if (!m) return null;
  const table = m[1] ?? "";
  const columns = (m[2] ?? "")
    .split(",")
    .map((c) => c.trim().replace(/^["']|["']$/g, ""))
    .filter((c) => c.length > 0);
  return { table, columns };
}

/** Rewrite the SQLite date/bucketing expressions the usage + errors repos use. */
function translateDateExprs(sql: string): string {
  let s = sql;
  // strftime('%Y-%m-%dT%H:%M', ts, 'localtime')
  s = s.replace(
    /strftime\('%Y-%m-%dT%H:%M',\s*([A-Za-z_][A-Za-z0-9_]*),\s*'localtime'\)/gi,
    (_m, col) =>
      `to_char((${col})::timestamptz AT TIME ZONE '${LOCAL_TZ}', 'YYYY-MM-DD"T"HH24:MI')`,
  );
  // strftime('%Y-%m-%dT%H:00', ts, 'localtime')
  s = s.replace(
    /strftime\('%Y-%m-%dT%H:00',\s*([A-Za-z_][A-Za-z0-9_]*),\s*'localtime'\)/gi,
    (_m, col) =>
      `to_char(date_trunc('hour', (${col})::timestamptz AT TIME ZONE '${LOCAL_TZ}'), 'YYYY-MM-DD"T"HH24:MI')`,
  );
  // strftime('%w', ts, '<shift>')  (shift = '+480 minutes' style literal)
  s = s.replace(
    /strftime\('%w',\s*([A-Za-z_][A-Za-z0-9_]*),\s*'([^']*)'\)/gi,
    (_m, col, shift) =>
      `CAST(to_char(((${col})::timestamptz + INTERVAL '${shift.replace(/^\+/, "")}') AT TIME ZONE 'UTC', 'ID') AS INTEGER)`,
  );
  // strftime('%H', ts, '<shift>')
  s = s.replace(
    /strftime\('%H',\s*([A-Za-z_][A-Za-z0-9_]*),\s*'([^']*)'\)/gi,
    (_m, col, shift) =>
      `CAST(to_char(((${col})::timestamptz + INTERVAL '${shift.replace(/^\+/, "")}') AT TIME ZONE 'UTC', 'HH24') AS INTEGER)`,
  );
  // date(<col>, '-6 days', 'weekday 1') → ISO Monday（::text 对齐 sqlite date() 的 TEXT 返回）
  s = s.replace(
    /date\(\s*["']?date["']?\s*,\s*'-6 days'\s*,\s*'weekday 1'\s*\)/gi,
    `date_trunc('week', ("date")::date)::date::text`,
  );
  // date(ts, :dayShift / $n) → UTC wall date + bound interval（::text 同上）
  s = s.replace(
    /date\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*,\s*(:\w+|\$\d+)\s*\)/gi,
    (_m, col, param) =>
      `(((((${col})::timestamptz AT TIME ZONE 'UTC')::date + (${param})::interval))::date::text)`,
  );
  return s;
}

/**
 * FTS5 support (session_search).
 *
 * The platform indexes a CJK unigram+bigram projection (services/search-text.ts) into
 * FTS5's `session_search` virtual table and queries it with `session_search MATCH ?`
 * plus FTS5's hidden `rank` (bm25) column. PostgreSQL has no FTS5, so:
 *
 *  - CREATE VIRTUAL TABLE ... USING fts5(...) → a plain table with the same columns
 *    plus a generated `body_tsv` tsvector column ('simple' config tokenizes a CJK run
 *    as one token — matching unicode61 — and the projection's U+0001 separators split
 *    it into exactly the pieces FTS5 indexed)
 *  - `session_search MATCH ?` → `body_tsv @@ to_tsquery('simple', ?)` — the VALUE at
 *    that parameter is an FTS5 expression (quoted phrases joined by AND), converted to
 *    tsquery syntax by the worker when it sees to_tsquery('simple', $n) in the SQL
 *  - bare `rank` → -ts_rank(body_tsv, to_tsquery('simple', $n)) (negated so ascending
 *    order = best first, matching bm25's more-negative-is-better), reusing the SAME
 *    parameter; `raw, rank` in a SELECT list keeps an `AS rank` alias so subqueries
 *    that pass it through keep working
 *  - LIKE → ILIKE (SQLite's LIKE is ASCII-case-insensitive; PG's is not)
 */
/**
 * SQLite's scalar 2-arg MAX(a,b)/MIN(a,b) are null-safe value comparisons; PG's
 * MAX/MIN are aggregates only. Exactly-2-argument calls map to GREATEST/LEAST
 * (single-arg aggregates untouched). Nested parens/strings handled.
 */
/**
 * Qualify bare references to SET-target columns inside ON CONFLICT DO UPDATE SET
 * expressions with the target table name (PG rejects the unqualified form).
 */
function qualifyDoUpdateSetRefs(sql: string): string {
  const setMatch = sql.match(/\bDO\s+UPDATE\s+SET\b/i);
  if (!setMatch || setMatch.index === undefined) return sql;
  const tblMatch = sql.match(
    /\bINSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)/i,
  );
  if (!tblMatch) return sql;
  // schema-qualified targets: only the TABLE segment is a valid RHS qualifier
  const target = tblMatch[1] ?? "";
  const table = target.split(".").pop() ?? target;
  const setStart = setMatch.index + setMatch[0].length;
  const setBody = sql.slice(setStart);
  // split assignments at top-level commas (string/paren aware)
  const parts: string[] = [];
  let depth = 0;
  let inStr = false;
  let cur = "";
  for (let i = 0; i < setBody.length; i += 1) {
    const ch = setBody[i];
    if (inStr) {
      cur += ch;
      if (ch === "'") {
        if (setBody[i + 1] === "'") {
          cur += "'";
          i += 1;
          continue;
        }
        inStr = false;
      }
      continue;
    }
    if (ch === "'") {
      inStr = true;
      cur += ch;
      continue;
    }
    if (ch === "(") depth += 1;
    else if (ch === ")") depth -= 1;
    if (ch === "," && depth === 0) {
      parts.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  if (cur.trim()) parts.push(cur);
  // SET target columns
  const targets: string[] = [];
  for (const p of parts) {
    const eq = p.indexOf("=");
    if (eq > 0) {
      const lhs = p.slice(0, eq).trim();
      const m = lhs.match(/^([A-Za-z_][A-Za-z0-9_]*)$/);
      if (m) targets.push(m[1] ?? "");
    }
  }
  if (targets.length === 0) return sql;
  const qualified = parts.map((p) => {
    const eq = p.indexOf("=");
    if (eq <= 0) return p;
    const lhs = p.slice(0, eq);
    const rhs = p.slice(eq + 1);
    let out = "";
    let i = 0;
    while (i < rhs.length) {
      const ch = rhs[i] ?? "";
      if (ch === "'") {
        let j = i + 1;
        while (j < rhs.length) {
          if (rhs[j] === "'") {
            if (rhs[j + 1] === "'") {
              j += 2;
              continue;
            }
            break;
          }
          j += 1;
        }
        out += rhs.slice(i, Math.min(j + 1, rhs.length));
        i = j + 1;
        continue;
      }
      if (/[A-Za-z_]/.test(ch)) {
        let j = i;
        while (j < rhs.length && /[A-Za-z0-9_]/.test(rhs[j] ?? "")) j += 1;
        const word = rhs.slice(i, j);
        const before = i > 0 ? rhs[i - 1] : "";
        const after = j < rhs.length ? rhs[j] : "";
        if (
          targets.includes(word) &&
          before !== "." &&
          before !== ":" && // :output is a NAMED PARAM — convertPlaceholders runs later
          before !== "$" &&
          after !== "("
        ) {
          out += `${table}.${word}`;
        } else {
          out += word;
        }
        i = j;
        continue;
      }
      out += ch;
      i += 1;
    }
    return `${lhs}=${out}`;
  });
  return sql.slice(0, setStart) + qualified.join(",");
}

function translateScalarMaxMin(sql: string): string {
  // Matches MAX(…) / MIN(…) whose parenthetical has ≤1 nesting level, then keeps
  // only exactly-2-arg forms (aggregates are 1-arg and pass through untouched).
  return sql.replace(
    /\b(MAX|MIN)\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)/gi,
    (m0, fn: string, args: string) => {
      let depth = 0;
      let commas = 0;
      let inStr = false;
      for (let i = 0; i < args.length; i += 1) {
        const ch = args[i];
        if (inStr) {
          if (ch === "'") {
            if (args[i + 1] === "'") {
              i += 1;
              continue;
            }
            inStr = false;
          }
        } else if (ch === "'") inStr = true;
        else if (ch === "(") depth += 1;
        else if (ch === ")") depth -= 1;
        else if (ch === "," && depth === 0) commas += 1;
      }
      if (commas !== 1) return m0;
      return `${fn.toUpperCase() === "MAX" ? "GREATEST" : "LEAST"}(${args})`;
    },
  );
}

function translateFts(sql: string): string {
  let s = sql;

  // CREATE VIRTUAL TABLE ... USING fts5(cols) → plain table + tsvector + indexes
  const vt = s.match(
    /CREATE\s+VIRTUAL\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?["']?([A-Za-z_][A-Za-z0-9_]*)["']?\s+USING\s+fts5\s*\(([\s\S]*?)\)\s*;?\s*$/i,
  );
  if (vt) {
    const table = vt[1] ?? "";
    const cols: Array<{ name: string; indexed: boolean }> = [];
    for (const raw of (vt[2] ?? "").split(",")) {
      const line = raw.trim();
      if (!line) continue;
      const m = line.match(/^["']?([A-Za-z_][A-Za-z0-9_]*)["']?(?:\s+UNINDEXED)?/i);
      if (!m) continue;
      cols.push({ name: m[1] ?? "", indexed: !/UNINDEXED/i.test(line) });
    }
    const INT_COLS = new Set(["file_index", "line_no"]);
    const defs = cols.map((c) => `${c.name} ${INT_COLS.has(c.name) ? "BIGINT" : "TEXT"}`);
    const parts = [
      `CREATE TABLE IF NOT EXISTS ${table} (\n  ${defs.join(",\n  ")},\n` +
        `  body_tsv tsvector GENERATED ALWAYS AS (to_tsvector('simple', coalesce(body, ''))) STORED\n)`,
      `CREATE INDEX IF NOT EXISTS idx_ss_body_tsv ON ${table} USING gin(body_tsv)`,
      `CREATE INDEX IF NOT EXISTS idx_ss_session ON ${table}(session_id, file_index, line_no)`,
    ];
    return parts.join(";\n") + ";";
  }

  // `<fts table> MATCH ?` → body_tsv @@ to_tsquery('simple', ?)
  // (placeholder conversion happens after this, so the ? becomes $n.)
  s = s.replace(/\b([A-Za-z_][A-Za-z0-9_]*)\s+MATCH\s+\?/gi, "body_tsv @@ to_tsquery('simple', ?)");

  // LIKE → ILIKE (ASCII case-insensitivity parity)
  s = s.replace(/\bLIKE\b/g, "ILIKE");

  // SQLite scalar 2-arg MAX(a,b)/MIN(a,b) → GREATEST/LEAST (PG aggregates are 1-arg)
  s = translateScalarMaxMin(s);

  // SQLite's IS / IS NOT do null-safe VALUE comparison; PostgreSQL only allows them
  // against NULL/TRUE/FALSE. Value forms map 1:1 to IS [NOT] DISTINCT FROM (same NULL
  // semantics). `IS NOT NULL` and `IS NULL` must pass through untouched.
  s = s.replace(
    /\bIS\s+NOT\s+(?!NULL\b)(?!DISTINCT\b)(?=(?:'[^']*'|\?|\$\d+|[A-Za-z_][\w.]*))/gi,
    "IS DISTINCT FROM ",
  );
  s = s.replace(
    /\bIS\s+(?!NOT\b)(?!NULL\b)(?!DISTINCT\b)(?!TRUE\b)(?!FALSE\b)(?!UNKNOWN\b)(?=(?:'[^']*'|\?|\$\d+|[A-Za-z_][\w.]*))/gi,
    "IS NOT DISTINCT FROM ",
  );

  return s;
}

/**
 * After placeholder conversion: rewrite bare `rank` in FTS queries. The MATCH rewrite
 * above guarantees the statement contains `body_tsv @@ to_tsquery('simple', $n)`.
 */
function translateFtsRank(sql: string): string {
  const m = sql.match(/body_tsv\s*@@\s*to_tsquery\('simple',\s*(\$\d+)\)/i);
  if (!m) return sql;
  const q = `(-ts_rank(body_tsv, to_tsquery('simple', ${m[1]})))`;
  let s = sql;
  // SELECT-list form: `raw, rank` → `raw, <expr> AS rank` — but NOT the pass-through
  // form in hitsFor's outer query (`raw, rank FROM (`), which refers to a subquery's
  // output column and has no body_tsv in scope.
  s = s.replace(/raw,\s*rank\b(?!\s*FROM\s*\()/gi, `raw, ${q} AS rank`);
  // Remaining bare rank: ORDER BY rank, min(rank), window ORDER BY rank.
  // `AS rank` aliases (produced above) and `rank FROM (` pass-throughs are excluded.
  s = s.replace(/(?<!\bAS )\brank\b(?!\s*FROM\s*\()/g, q);
  return s;
}

/**
 * SQLite is lax about bare columns in aggregate queries (`SELECT session_id, agent_id,
 * count(*) ... GROUP BY session_id` picks an arbitrary agent_id); PostgreSQL requires
 * every selected bare column to be grouped or aggregated. For each selected bare column
 * that is neither, append it to the GROUP BY list. Functionally dependent columns (a
 * session's agent) group identically, so the result set is unchanged.
 */
function fixGroupBy(sql: string): string {
  const gbMatch = sql.match(/\bGROUP\s+BY\s+/i);
  if (!gbMatch || gbMatch.index === undefined) return sql;
  const gbStart = gbMatch.index + gbMatch[0].length;
  // GROUP BY list runs until ORDER BY / LIMIT / HAVING / end (top level).
  const tail = sql.slice(gbStart);
  const tailStop = tail.search(/\b(ORDER\s+BY|LIMIT|HAVING)\b/i);
  const gbList = (tailStop === -1 ? tail : tail.slice(0, tailStop)).trim();
  const grouped = new Set(
    gbList
      .split(",")
      .map((c) =>
        c
          .trim()
          .replace(/^["']|["']$/g, "")
          .toLowerCase(),
      )
      .filter(Boolean),
  );
  // SELECT list: between the first top-level SELECT and FROM.
  const selMatch = sql.match(/\bSELECT\b/i);
  if (!selMatch || selMatch.index === undefined) return sql;
  const fromMatch = sql.slice(selMatch.index).match(/\bFROM\b/i);
  if (!fromMatch || fromMatch.index === undefined) return sql;
  const selectList = sql.slice(selMatch.index + 6, selMatch.index + fromMatch.index);
  const items = splitTopLevel(selectList);
  const toAdd: string[] = [];
  for (const raw of items) {
    const item = raw.trim();
    if (!item) continue;
    // Aggregates are fine as-is.
    if (/\b(count|sum|min|max|avg|total|group_concat)\s*\(/i.test(item)) continue;
    // Strip a trailing alias; the alias itself counts as grouped (GROUP BY key).
    const aliasMatch = item.match(/\s+AS\s+["']?([\w]+)["']?\s*$/i);
    const expr = (aliasMatch ? item.slice(0, aliasMatch.index) : item).trim();
    if (aliasMatch && grouped.has((aliasMatch[1] ?? "").toLowerCase())) continue;
    // Only bare column references (optionally table-qualified).
    if (!/^["']?[\w]+["']?(?:\.["']?[\w]+["']?)?$/.test(expr)) continue;
    const bare = expr.replace(/["']/g, "").toLowerCase();
    const col = bare.includes(".") ? bare.split(".").pop()! : bare;
    if (grouped.has(bare) || grouped.has(col)) continue;
    if (!toAdd.some((c) => c.toLowerCase() === expr.toLowerCase())) toAdd.push(expr);
  }
  if (toAdd.length === 0) return sql;
  const newList = gbList ? `${gbList}, ${toAdd.join(", ")}` : toAdd.join(", ");
  // Rebuild: [prefix incl. "GROUP BY "] + new list + [remainder from the original
  // tail boundary, with a separating space so "…, agent_id ORDER BY" stays valid].
  const remainder = tailStop === -1 ? "" : ` ${tail.slice(tailStop)}`;
  return sql.slice(0, gbStart) + newList + remainder;
}

/** Split on top-level commas (paren/quote aware). */
function splitTopLevel(s: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let cur = "";
  let i = 0;
  while (i < s.length) {
    const ch = s[i];
    if (ch === "'" || ch === '"') {
      const q = ch;
      cur += ch;
      i += 1;
      while (i < s.length) {
        cur += s[i];
        if (s[i] === q) {
          if (s[i + 1] === q) {
            cur += s[i + 1];
            i += 2;
            continue;
          }
          i += 1;
          break;
        }
        i += 1;
      }
      continue;
    }
    if (ch === "(") depth += 1;
    if (ch === ")") depth = Math.max(0, depth - 1);
    if (ch === "," && depth === 0) {
      out.push(cur);
      cur = "";
      i += 1;
      continue;
    }
    cur += ch;
    i += 1;
  }
  if (cur.trim()) out.push(cur);
  return out;
}

export interface TranslateCtx {
  /** Primary-key columns for a table, from the PG catalog (async, cached by caller). */
  pkOf(table: string): string[] | null;
}

/**
 * Translate one statement. Returns null when the statement is a no-op under PG
 * (PRAGMAs PG does not need).
 */
export function translateStatement(sql: string, ctx: TranslateCtx): string | null {
  let s = sql.trim();
  if (!s) return null;

  // PRAGMAs that are no-ops on PG
  if (
    /^PRAGMA\s+(journal_mode|foreign_keys|busy_timeout|synchronous|page_size|cache_size|temp_store|wal_autocheckpoint)/i.test(
      s,
    )
  ) {
    return null;
  }
  // PRAGMA user_version / table_info are rewritten by the shim before reaching here.

  // BEGIN IMMEDIATE → BEGIN (PG has no IMMEDIATE; plain BEGIN already allows writes)
  s = s.replace(/^BEGIN\s+IMMEDIATE/i, "BEGIN");
  s = s.replace(/^BEGIN\s+EXCLUSIVE/i, "BEGIN");
  s = s.replace(/^BEGIN\s+DEFERRED/i, "BEGIN");

  // ALTER TABLE ... ADD COLUMN → IF NOT EXISTS (ensureColumn guards anyway)
  s = s.replace(
    /^ALTER\s+TABLE\s+([A-Za-z_][A-Za-z0-9_."]*)\s+ADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS)/i,
    "ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ",
  );

  // INTEGER PRIMARY KEY AUTOINCREMENT → identity column
  s = s.replace(
    /INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi,
    "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  );

  // INSERT OR REPLACE / OR IGNORE
  const orMatch = s.match(
    /^INSERT\s+OR\s+(REPLACE|IGNORE)\s+INTO\s+(["']?)([A-Za-z_][A-Za-z0-9_]*)\2\s*\(/i,
  );
  if (orMatch) {
    const verb = (orMatch[1] ?? "").toUpperCase();
    const table = orMatch[3] ?? "";
    const parsed = parseInsert(s);
    if (!parsed) throw new Error(`pg-shim: cannot parse INSERT for ${table}: ${s.slice(0, 120)}`);
    if (verb === "IGNORE") {
      s = s.replace(/^INSERT\s+OR\s+IGNORE\s+INTO/i, "INSERT INTO") + " ON CONFLICT DO NOTHING";
    } else {
      const pk = ctx.pkOf(table);
      if (!pk || pk.length === 0) {
        throw new Error(
          `pg-shim: no primary key known for ${table} (INSERT OR REPLACE needs ON CONFLICT target)`,
        );
      }
      const conflictCols = pk.join(", ");
      const updates = parsed.columns
        .filter((c) => !pk.includes(c))
        .map((c) => `${c} = EXCLUDED.${c}`)
        .join(", ");
      s = s.replace(/^INSERT\s+OR\s+REPLACE\s+INTO/i, "INSERT INTO");
      if (updates) {
        s += ` ON CONFLICT (${conflictCols}) DO UPDATE SET ${updates}`;
      } else {
        s += ` ON CONFLICT (${conflictCols}) DO NOTHING`;
      }
    }
  }

  // ON CONFLICT DO UPDATE: PG resolves an unqualified RHS reference that shares a
  // name with its own SET target as AMBIGUOUS ("column reference x is ambiguous");
  // SQLite resolves it to the existing row. Qualify such refs with the target table.
  s = qualifyDoUpdateSetRefs(s);

  // Date-function rewrites (usage/errors repos)
  s = translateDateExprs(s);

  // FTS5 rewrites (session_search): MATCH → tsvector, LIKE → ILIKE.
  // CREATE VIRTUAL TABLE ... USING fts5(...) returns its own DDL bundle outright.
  if (/CREATE\s+VIRTUAL\s+TABLE/i.test(s)) {
    return translateFts(s);
  }
  s = translateFts(s);

  // Placeholders last (so ON CONFLICT SQL added above has none of its own)
  const { sql: withParams } = convertPlaceholders(s);
  // FTS rank rewrite needs the final $n indices.
  const withRank = translateFtsRank(withParams);
  // SQLite allows bare columns under GROUP BY; PostgreSQL does not.
  return fixGroupBy(withRank);
}

/** Translate a full script (exec): every statement, no-ops dropped. */
export function translateScript(sql: string, ctx: TranslateCtx): string {
  const parts: string[] = [];
  for (const stmt of splitStatements(sql)) {
    const t = translateStatement(stmt, ctx);
    if (t) parts.push(t);
  }
  return parts.join(";\n") + (parts.length ? ";" : "");
}
