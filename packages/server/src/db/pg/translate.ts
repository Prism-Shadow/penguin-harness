/**
 * Translate one statement. Returns null when the statement is a no-op under PG
 * (PRAGMAs PG does not need).
 */
export function translateStatement(sql: string, ctx: TranslateCtx): string | null {
  let s = sql.trim();
  if (!s) return null;

  // PRAGMAs that are no-ops on PG
  if (/^PRAGMA\s+(journal_mode|foreign_keys|busy_timeout|synchronous|page_size|cache_size|temp_store|wal_autocheckpoint)/i.test(s)) {
    return null;
  }
  // PRAGMA user_version / table_info are rewritten by the shim before reaching here.

  // BEGIN IMMEDIATE → BEGIN (PG has no IMMEDIATE; plain BEGIN already allows writes)
  s = s.replace(/^BEGIN\s+IMMEDIATE/i, "BEGIN");
  s = s.replace(/^BEGIN\s+EXCLUSIVE/i, "BEGIN");
  s = s.replace(/^BEGIN\s+DEFERRED/i, "BEGIN");

  // ALTER TABLE ... ADD COLUMN → IF NOT EXISTS (ensureColumn guards anyway)
  s = s.replace(/^ALTER\s+TABLE\s+([A-Za-z_][A-Za-z0-9_."]*)\s+ADD\s+COLUMN\s+(?!IF\s+NOT\s+EXISTS)/i, "ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ");

  // INTEGER PRIMARY KEY AUTOINCREMENT → identity column
  s = s.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");

  // INSERT OR REPLACE / OR IGNORE
  const orMatch = s.match(/^INSERT\s+OR\s+(REPLACE|IGNORE)\s+INTO\s+(["']?)([A-Za-z_][A-Za-z0-9_]*)\2\s*\(/i);
  if (orMatch) {
    const verb = orMatch[1].toUpperCase();
    const table = orMatch[3];
    const parsed = parseInsert(s);
    if (!parsed) throw new Error(`pg-shim: cannot parse INSERT for ${table}: ${s.slice(0, 120)}`);
    if (verb === "IGNORE") {
      s = s.replace(/^INSERT\s+OR\s+IGNORE\s+INTO/i, "INSERT INTO") + " ON CONFLICT DO NOTHING";
    } else {
      const pk = ctx.pkOf(table);
      if (!pk || pk.length === 0) {
        throw new Error(`pg-shim: no primary key known for ${table} (INSERT OR REPLACE needs ON CONFLICT target)`);
      }
      const conflictCols = pk.join(", ");
      const updates = parsed.columns
        .filter((c) => !pk.includes(c))
        .map((c) => `${c} = EXCLUDED.${c}`)
        .join(", ");
      s = s.replace(/^INSERT\s+OR\s+REPLACE\s+INTO/i, "INSERT INTO");
      if (updates) {
        s += ` ON CONFLICT (${conflictCols}) DO UPDATE SET ${updates}`;
      } else {
        s += ` ON CONFLICT (${conflictCols}) DO NOTHING`;
      }
    }
  }

  // SQLite scalar max(a, b, …) → GREATEST (PG has no multi-argument max()).
  s = translateScalarMax(s);

  // ON CONFLICT DO UPDATE SET: qualify bare target-table columns on the RHS
  // (PG treats unqualified references as ambiguous with EXCLUDED; sqlite
  // requires them bare). See function doc.
  s = qualifyUpsertSetColumns(s);

  // Date-function rewrites (usage/errors repos)
  s = translateDateExprs(s);

  // FTS5 rewrites (session_search): MATCH → tsvector, LIKE → ILIKE.
  // CREATE VIRTUAL TABLE ... USING fts5(...) returns its own DDL bundle outright.
  if (/CREATE\s+VIRTUAL\s+TABLE/i.test(s)) {
    return translateFts(s);
  }
  s = translateFts(s);

  // Placeholders last (so ON CONFLICT SQL added above has none of its own)
  const { sql: withParams } = convertPlaceholders(s);
  // FTS rank rewrite needs the final $n indices.
  const withRank = translateFtsRank(withParams);
  // SQLite allows bare columns under GROUP BY; PostgreSQL does not.
  return fixGroupBy(withRank);
}

/** Translate a full script (exec): every statement, no-ops dropped. */
export function translateScript(sql: string, ctx: TranslateCtx): string {
  const parts: string[] = [];
  for (const stmt of splitStatements(sql)) {
    const t = translateStatement(stmt, ctx);
    if (t) parts.push(t);
  }
  return parts.join(";\n") + (parts.length ? ";" : "");
}
